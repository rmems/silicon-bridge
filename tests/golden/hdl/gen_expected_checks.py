"""Generate SystemVerilog checks from the golden ``expected.json`` files.

``tb_readmemh_contract.sv`` hardcodes a few spot-check words. This script makes
the simulation also compare the words that ``$readmemh`` actually loaded against
the independently specified words in ``expected.json``, so a drift between
``expected.json`` and the committed ``.mem`` images fails the HDL run.

Output is an include file of ``check_hex(...)`` calls that the testbench pulls
in when compiled with ``-DEXPECTED_JSON_CHECKS``. Standard library only.

Usage: gen_expected_checks.py <golden_root> <out.svh>
"""

import json
import re
import sys
from pathlib import Path

HEX_WORD = re.compile(r"^[0-9A-F]{4}$")


def word(value: str, where: str) -> str:
    if not isinstance(value, str) or not HEX_WORD.match(value):
        sys.exit(f"gen_expected_checks: {where}: {value!r} is not a 4-digit uppercase hex word")
    return value


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit("usage: gen_expected_checks.py <golden_root> <out.svh>")
    root = Path(sys.argv[1])
    out = Path(sys.argv[2])
    lines = ["// Generated by gen_expected_checks.py from expected.json. Do not edit."]
    count = 0

    # generic_4x6: every hidden weight word, row-major.
    generic = json.loads((root / "generic_4x6/expected.json").read_text())
    words = generic["row_major_weight_hex"]
    want = generic["num_neurons"] * generic["num_channels"]
    if len(words) != want:
        sys.exit(f"gen_expected_checks: generic_4x6 has {len(words)} words, expected {want}")
    for addr, value in enumerate(words):
        value = word(value, f"generic_4x6 row_major_weight_hex[{addr}]")
        lines.append(
            f'check_hex(u_generic.mem[{addr}], 16\'h{value}, '
            f'"expected.json generic_4x6 row_major_weight_hex[{addr}]");'
        )
        count += 1

    # spikenaut_16: pinned hidden addresses (addr = neuron * channels + channel).
    spk = json.loads((root / "spikenaut_16/expected.json").read_text())
    channels = spk["num_channels"]
    for entry in spk["pinned_hidden_addresses"]:
        n, c = entry["neuron"], entry["channel"]
        if not (0 <= n < spk["num_neurons"] and 0 <= c < channels):
            sys.exit(f"gen_expected_checks: spikenaut_16 pinned ({n},{c}) out of range")
        value = word(entry["hex"], f"spikenaut_16 pinned ({n},{c})")
        addr = n * channels + c
        lines.append(
            f'check_hex(u_hidden.mem[{addr}], 16\'h{value}, '
            f'"expected.json spikenaut_16 pinned_hidden_addresses n{n} c{c}");'
        )
        count += 1

    lines.append(f"expected_json_checks = {count};")
    out.write_text("\n".join(lines) + "\n")
    print(f"gen_expected_checks: {count} word checks from expected.json")


if __name__ == "__main__":
    main()
